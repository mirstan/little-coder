"""harbor_tb_ingest.py: tb tested against a REAL captured terminal-bench run
(tests/fixtures/real_tb_run/), harbor tested against a REAL captured harbor
run (tests/fixtures/real_harbor_run/) -- both generated by actually running
the real CLI (`tb run` / `harbor run`) against the hello-world task with pi
routed through fake_pi.py via LITTLE_CODER_PI_BIN_OVERRIDE. No synthetic
guessing; harbor and tb turned out to have GENUINELY DIFFERENT real
structures, confirmed by running both, not assumed from one shared format.

tb structure (see test file docstring further down, unchanged from the
earlier rewrite):
  <log_root>/<task_id>/<task_id>.N-of-M.<ts>/results.json     (plural) per-trial: is_resolved
  <log_root>/<task_id>/<task_id>.N-of-M.<ts>/agent-logs/*.log

harbor structure (CONFIRMED DIFFERENT -- single-level trial dirs, singular
result.json, richer structured agent_result.metadata, reward-based ground
truth):
  <log_root>/<trial_name>/result.json     (singular) per-trial:
    agent_result.metadata: {stop_reason, n_tool_calls, n_turns, n_compactions, n_notifications}
    verifier_result.rewards.reward: float (0.0/1.0) -- GROUND TRUTH
    task_name: "org/name" (e.g. "hello-world/hello-world")
  <log_root>/<trial_name>/agent/*.log     (singular "agent", not "agent-logs")
"""
