"""harbor_tb_ingest.py, rewritten test-first against a REAL captured
terminal-bench run (tests/fixtures/real_tb_run/, generated by actually
running `tb run` against the hello-world task with pi routed through
fake_pi.py via LITTLE_CODER_PI_BIN_OVERRIDE -- no synthetic guessing).

Confirmed real structure (differs from the flat *.log layout originally
assumed):
  <log_root>/results.json                                    run-level aggregate
  <log_root>/<task_id>/<task_id>.N-of-M.<ts>/results.json     per-trial, ground-truth is_resolved
  <log_root>/<task_id>/<task_id>.N-of-M.<ts>/agent-logs/*.log little-coder's own log
    (=== stop_reason: X ===, === assistant text ===, >> tool(args) / << result)

Real, confirmed bug this rewrite fixes: the original flat `*.log` glob
matched terminal-bench's own top-level run.log (task_id="run",
stop_reason="unknown") instead of the real nested agent log, and the
original success-from-stop_reason approximation disagreed with the real
ground truth (fake_pi's "clean" mode always reports stop_reason=agent_end
even when the task actually failed -- is_resolved=false in the real
results.json for this exact fixture).
"""
from pathlib import Path

from benchmarks.self_improve.ingest import harbor_tb_ingest

FIXTURE_ROOT = Path(__file__).parent / "fixtures" / "real_tb_run"


def test_load_finds_the_real_nested_trial_not_the_top_level_run_log():
    trajs = harbor_tb_ingest.load(FIXTURE_ROOT, benchmark="tb")
    assert len(trajs) == 1
    assert trajs[0].task_id == "hello-world"


def test_load_uses_is_resolved_as_ground_truth_not_stop_reason_approximation():
    """The real fixture: stop_reason=agent_end (fake_pi's clean mode always
    reports this) but is_resolved=false (the task actually failed -- hello.txt
    was never created). Ground truth must win."""
    trajs = harbor_tb_ingest.load(FIXTURE_ROOT, benchmark="tb")
    traj = trajs[0]
    assert traj.stop_reason == "agent_end"
    assert traj.success is False


def test_load_sets_benchmark_from_argument():
    trajs = harbor_tb_ingest.load(FIXTURE_ROOT, benchmark="harbor")
    assert trajs[0].benchmark == "harbor"


def test_load_extracts_tool_calls_into_summary():
    trajs = harbor_tb_ingest.load(FIXTURE_ROOT, benchmark="tb")
    assert "read" in trajs[0].summarized_transcript


def test_load_raw_paths_point_to_real_files():
    trajs = harbor_tb_ingest.load(FIXTURE_ROOT, benchmark="tb")
    for path_str in trajs[0].raw_paths.values():
        assert Path(path_str).exists()


def test_load_handles_empty_directory(tmp_path):
    assert harbor_tb_ingest.load(tmp_path, benchmark="harbor") == []


def test_load_handles_run_with_no_trial_results_gracefully(tmp_path):
    """A task_id directory exists but has no trial subdirectory with a
    results.json (e.g. an interrupted run) -- must skip, not crash."""
    (tmp_path / "some-task").mkdir()
    trajs = harbor_tb_ingest.load(tmp_path, benchmark="harbor")
    assert trajs == []


def test_load_handles_malformed_trial_results_json(tmp_path):
    task_dir = tmp_path / "broken-task" / "broken-task.1-of-1.ts"
    task_dir.mkdir(parents=True)
    (task_dir / "results.json").write_text("not valid json{{{")
    (task_dir / "agent-logs").mkdir()
    (task_dir / "agent-logs" / "little_coder.log").write_text("=== stop_reason: agent_end ===\n")
    trajs = harbor_tb_ingest.load(tmp_path, benchmark="harbor")
    assert trajs == []  # skipped, not crashed


def test_load_components_used_is_empty():
    """No notification capture exists in this log format at all today --
    lock this in explicitly, same rationale as the aider_polyglot gap."""
    trajs = harbor_tb_ingest.load(FIXTURE_ROOT, benchmark="tb")
    assert trajs[0].components_used == []
